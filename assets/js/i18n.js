// Traduz uma frase da interface; valores em {chave} são substituídos depois da tradução.
function t(text, values) {
  const translated = LANG === "en" ? EN[text] ?? text : text;
  return values ? translated.replace(/\{(\w+)\}/g, (match, key) => (key in values ? values[key] : match)) : translated;
}

// O HTML é escrito em português; em inglês, textos e atributos fixos são trocados uma vez na carga.
function translateStaticPage() {
  document.documentElement.lang = LANG === "en" ? "en" : "pt-BR";
  if (LANG !== "en") return;
  const translateValue = (value) => {
    const key = value.replace(/\s+/g, " ").trim();
    if (!key || !(key in EN)) return null;
    const [, before, after] = value.match(/^(\s*)[\s\S]*?(\s*)$/);
    return `${before}${EN[key]}${after}`;
  };
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const translated = translateValue(node.nodeValue);
    if (translated !== null) node.nodeValue = translated;
  }
  document.querySelectorAll("[placeholder], [aria-label], [title], [data-title]").forEach((element) => {
    ["placeholder", "aria-label", "title", "data-title"].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      const translated = translateValue(element.getAttribute(attribute));
      if (translated !== null) element.setAttribute(attribute, translated);
    });
  });
  document.title = t(document.title);
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = t(description.content);
}

function setLanguage(lang) {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (error) {
    console.error("Não foi possível salvar o idioma escolhido.", error);
  }
  window.location.reload();
}
